// One-off: pull latin woff2 subsets from Google Fonts and self-host them.
import { mkdir, writeFile } from "node:fs/promises";

const UA =
  "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0 Safari/537.36";

const families = [
  {
    family: "Oswald",
    css: "Oswald:wght@400;500;600;700",
    faces: [
      ["400", "400"],
      ["500", "500"],
      ["600", "600"],
      ["700", "700"],
    ],
  },
  {
    family: "Newsreader",
    css: "Newsreader:ital,opsz,wght@0,6..72,400;0,6..72,500;0,6..72,600;1,6..72,400;1,6..72,500",
    faces: [
      ["400", "400"],
      ["500", "500"],
      ["600", "600"],
      ["400i", "400"],
      ["500i", "500"],
    ],
  },
  {
    family: "DM Mono",
    css: "DM+Mono:wght@400;500",
    faces: [
      ["400", "400"],
      ["500", "500"],
    ],
  },
];

await mkdir("public/fonts", { recursive: true });

let out = "/* Self-hosted latin subsets. Generated by scripts/fetch-fonts.mjs */\n";

for (const fam of families) {
  const url = `https://fonts.googleapis.com/css2?family=${fam.css}&display=swap`;
  const css = await fetch(url, { headers: { "User-Agent": UA } }).then((r) => r.text());

  // Split into @font-face blocks and keep the ones flagged /* latin */
  const blocks = css.split("/* ").slice(1);
  const latin = blocks.filter((b) => b.startsWith("latin */"));

  for (const block of latin) {
    const src = block.match(/src:\s*url\((https:[^)]+\.woff2)\)/);
    const weight = block.match(/font-weight:\s*([^;]+);/);
    const style = block.match(/font-style:\s*([^;]+);/);
    if (!src || !weight) continue;
    const w = weight[1].trim();
    const st = (style?.[1] ?? "normal").trim();
    const tag = `${fam.family.replace(/\s+/g, "")}-${w}${st === "italic" ? "i" : ""}`;
    const file = `${tag}.woff2`;
    const res = await fetch(src[1], { headers: { "User-Agent": UA } });
    if (!res.ok) throw new Error(`font fetch failed ${src[1]} ${res.status}`);
    await writeFile(`public/fonts/${file}`, Buffer.from(await res.arrayBuffer()));
    out += `@font-face{font-family:'${fam.family}';font-style:${st};font-weight:${w};font-display:swap;src:url('/fonts/${file}') format('woff2');unicode-range:U+0000-00FF,U+0131,U+0152-0153,U+02BB-02BC,U+02C6,U+02DA,U+02DC,U+2000-206F,U+2074,U+20AC,U+2122,U+2191,U+2193,U+2212,U+2215,U+FEFF,U+FFFD;}\n`;
  }
  console.log("fonts:", fam.family, latin.length, "latin faces");
}

await writeFile("src/fonts.css", out);
console.log("wrote src/fonts.css");
